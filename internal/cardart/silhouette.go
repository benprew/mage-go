func parseLines(lines []string) [24][24]bool {
	var grid [24][24]bool
	for y, line := range lines {
		if y >= 24 {
			break
		}
		for x, ch := range line {
			if x >= 24 {
				break
			}
			if ch == '#' {
				grid[y][x] = true
			}
		}
	}
	return grid
}
