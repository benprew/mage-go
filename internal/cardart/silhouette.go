package cardart

// getSilhouette returns a 24x24 boolean mask for the given card type.
// true = pixel is part of the silhouette.
func getSilhouette(t CardType) [24][24]bool {
	switch t {
	case TypeCreature:
		return creatureSilhouette()
	case TypeArtifact:
		return artifactSilhouette()
	case TypeEnchantment:
		return enchantmentSilhouette()
	case TypeInstant:
		return instantSilhouette()
	case TypeSorcery:
		return sorcerySilhouette()
	case TypeLand:
		return landSilhouette()
	default:
		return creatureSilhouette()
	}
}

